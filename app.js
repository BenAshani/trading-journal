function autoResize(el) {
  el.style.height = 'auto';
  el.style.height = el.scrollHeight + 'px';
}

function openFAModal(ticker) {
  faCurrentTicker = ticker;
  if (!faDataStore[ticker]) faDataStore[ticker] = { bizDesc: '', bizMoat: '', bizRisks: '', reports: [] };
  const d = faDataStore[ticker];

  // Auto-populate from built-in data if empty
  let changed = false;
  if (!d.bizDesc && COMPANY_DESC[ticker])  { d.bizDesc  = COMPANY_DESC[ticker];  changed = true; }
  if (!d.bizMoat && COMPANY_MOAT[ticker])  { d.bizMoat  = COMPANY_MOAT[ticker];  changed = true; }
  if (!d.bizRisks && COMPANY_RISKS[ticker]) { d.bizRisks = COMPANY_RISKS[ticker]; changed = true; }
  if (changed) saveFAData();

  document.getElementById('fa-biz-desc').value  = d.bizDesc  || '';
  document.getElementById('fa-biz-moat').value  = d.bizMoat  || '';
  document.getElementById('fa-biz-risks').value = d.bizRisks || '';
  document.getElementById('fa-ticker-lbl').textContent = ticker;
  document.getElementById('fa-note-lbl').textContent   = (watchlist.find(w => w.ticker === ticker) || {}).note || '';
  const q = priceCache[ticker] || null;
  document.getElementById('fa-price-lbl').textContent = q ? '$' + q.price.toFixed(2) : '—';
  if (q) {
    const col = pnlCol(q.changesPercentage);
    document.getElementById('fa-chg-lbl').innerHTML = `<span style="color:${col}">${signStr(q.changesPercentage)}${q.changesPercentage.toFixed(2)}% (${signStr(q.change)}${q.change.toFixed(2)}$)</span>`;
  } else { document.getElementById('fa-chg-lbl').textContent = ''; }
  document.getElementById('fa-autosave-lbl').innerHTML = '<i class="ti ti-device-floppy" style="font-size:11px"></i>שמירה אוטומטית';
  renderFAReports();
  document.getElementById('fa-overlay').classList.add('open');

  // Scroll to top and auto-resize all textareas
  const body = document.querySelector('.fa-body');
  if (body) body.scrollTop = 0;
  requestAnimationFrame(() => {
    document.querySelectorAll('.fa-autoresize').forEach(autoResize);
  });

  // Fetch next earnings date
  fetchNextEarnings(ticker);
}

async function fetchNextEarnings(ticker) {
  const el = document.getElementById('fa-earnings-countdown');
  if (!el) return;
  el.textContent = '';
  const key = getKey();
  if (!key) return;
  try {
    const today = new Date();
    const from  = today.toISOString().split('T')[0];
    const to    = new Date(today.getTime() + 365 * 86400000).toISOString().split('T')[0];
    const url   = `https://finnhub.io/api/v1/calendar/earnings?symbol=${encodeURIComponent(ticker)}&from=${from}&to=${to}&token=${key}`;
    const res   = await fetch(url);
    if (!res.ok) return;
    const data  = await res.json();
    const next  = data?.earningsCalendar?.[0];
    if (!next?.date) return;
    const days = Math.ceil((new Date(next.date) - today) / 86400000);
    const badge = days <= 7  ? 'ea-soon' :
                  days <= 30 ? 'ea-near' : 'ea-far';
    el.innerHTML = `<span class="fa-ea-badge ${badge}"><i class="ti ti-calendar-event" style="font-size:11px"></i>${next.date} — עוד ${days} ימים לדוח</span>`;
  } catch { /* silent */ }
}

