function faEffRatio(opex, rev) {
  const o = parseFloat(opex), r = parseFloat(rev);
  if (isNaN(o) || isNaN(r) || r === 0) return null;
  return o / r * 100;
}

function faIncSectionHTML(r, sfx, revC, revP, opC, opP, hdrCurr, hdrPrev) {
  const yoyPct = (curr, prev, invert) => {
    const c = parseFloat(curr), p = parseFloat(prev);
    if (isNaN(c) || isNaN(p) || p === 0) return { text: '—', cls: '' };
    const pct = ((c - p) / Math.abs(p) * 100).toFixed(1);
    const cls = (pct > 0 !== invert) ? 'inc-pos' : 'inc-neg';
    return { text: (pct > 0 ? '+' : '') + pct + '%', cls };
  };
  const effTag = (id, opex, rev) => {
    const ratio = faEffRatio(opex, rev);
    return `<div class="fai-eff-tag" id="${id}">${ratio !== null ? ratio.toFixed(1) + '%' : '—'}</div>`;
  };
  const effDelta = (id, cO, cR, pO, pR) => {
    const curr = faEffRatio(cO, cR), prev = faEffRatio(pO, pR);
    let text = '—', cls = '';
    if (curr !== null && prev !== null) {
      const d = curr - prev;
      text = (d > 0 ? '+' : '') + d.toFixed(1) + ' נ"א';
      cls = d < 0 ? 'inc-pos' : d > 0 ? 'inc-neg' : '';
    }
    return `<div class="fai-pct fai-eff-delta ${cls}" id="${id}">${text}</div>`;
  };
  const revYoy  = yoyPct(r[revC], r[revP], false);
  const opexYoy = yoyPct(r[opC],  r[opP],  true);
  return `
    <div class="fai-header">
      <div class="fai-lbl"></div>
      <div class="fai-col-hdr">${hdrCurr}</div>
      <div class="fai-col-hdr">${hdrPrev}</div>
      <div class="fai-col-hdr">שינוי %</div>
    </div>
    <div class="fai-row">
      <div class="fai-lbl">הכנסות</div>
      <div class="fai-inp-cell">
        <input class="fai-inp" type="number" step="0.01" placeholder="—" value="${escHtml(r[revC]||'')}"
          oninput="faIncField('${r.id}','${revC}',this.value,'${sfx}')">
        ${effTag(`fai-eff-curr-${r.id}-${sfx}`, r[opC], r[revC])}
      </div>
      <div class="fai-inp-cell">
        <input class="fai-inp" type="number" step="0.01" placeholder="—" value="${escHtml(r[revP]||'')}"
          oninput="faIncField('${r.id}','${revP}',this.value,'${sfx}')">
        ${effTag(`fai-eff-prev-${r.id}-${sfx}`, r[opP], r[revP])}
      </div>
      <div class="fai-pct ${revYoy.cls}" id="fai-pct-${r.id}-${revC}">${revYoy.text}</div>
    </div>
    <div class="fai-row" style="border-bottom:none">
      <div class="fai-lbl">הוצאות תפעוליות</div>
      <input class="fai-inp" type="number" step="0.01" placeholder="—" value="${escHtml(r[opC]||'')}"
        oninput="faIncField('${r.id}','${opC}',this.value,'${sfx}')">
      <input class="fai-inp" type="number" step="0.01" placeholder="—" value="${escHtml(r[opP]||'')}"
        oninput="faIncField('${r.id}','${opP}',this.value,'${sfx}')">
      <div class="fai-pct ${opexYoy.cls}" id="fai-pct-${r.id}-${opC}">${opexYoy.text}</div>
    </div>
    <div class="fai-eff-footer">
      <span class="fai-eff-footer-lbl">יחס הוצ׳/הכנ׳ (התייעלות)</span>
      ${effDelta(`fai-eff-delta-${r.id}-${sfx}`, r[opC], r[revC], r[opP], r[revP])}
    </div>`;
}

