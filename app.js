  open.forEach(t => {
    const cp = (prices[t.ticker] || priceCache[t.ticker])?.price;
    if (cp) flash(document.getElementById('cprice-' + t.id), cp, t.ticker);
  });

  const sp = document.getElementById('sum-pnl');
