function migrateBizDescs() {
  const isOldTemplate = s => !s || s.includes('(מלא כאן') || s.includes('💡 מה עושה');
  let changed = false;
  const allTickers = new Set([...Object.keys(COMPANY_DESC), ...Object.keys(COMPANY_MOAT), ...Object.keys(COMPANY_RISKS)]);
  allTickers.forEach(ticker => {
    if (!faDataStore[ticker]) faDataStore[ticker] = { bizDesc: '', bizMoat: '', bizRisks: '', reports: [] };
    const d = faDataStore[ticker];
    if (isOldTemplate(d.bizDesc)  && COMPANY_DESC[ticker])  { d.bizDesc  = COMPANY_DESC[ticker];  changed = true; }
    if (!d.bizMoat  && COMPANY_MOAT[ticker])                 { d.bizMoat  = COMPANY_MOAT[ticker];  changed = true; }
    if (!d.bizRisks && COMPANY_RISKS[ticker])                { d.bizRisks = COMPANY_RISKS[ticker]; changed = true; }
  });
  if (changed) saveFAData();
}

