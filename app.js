async function loadPortfolio() {
  const btn = document.getElementById('port-ref-btn');
  btn.classList.add('spinning');
  setDot('port', 'amber', 'טוען...');

  const holdings = portfolio.filter(h => (h.remainingQty || h.qty) > 0);
  document.getElementById('ps-cnt').textContent = holdings.length;

  const investCash = getInvestCash();
  syncCashCard(investCash);

  if (!holdings.length) {
    document.getElementById('port-holdings').innerHTML = '<div class="empty-state"><i class="ti ti-briefcase"></i><p style="margin-bottom:0.65rem">אין החזקות עדיין</p><button class="add-btn" style="display:inline-flex" onclick="openHM()"><i class="ti ti-plus"></i>הוסף החזקה ראשונה</button></div>';
    ['ps-val','ps-cost','ps-pnl','ps-ret'].forEach(id => { document.getElementById(id).textContent = '—'; document.getElementById(id).style.color = ''; });
    if (investCash) {
      document.getElementById('ps-val').textContent = '$' + Math.round(investCash).toLocaleString();
      setPsValSub('מזומן בלבד');
    } else setPsValSub('');
    document.getElementById('port-charts-row').style.display = 'none';
    setDot('port', 'off', 'ממתין');
    btn.classList.remove('spinning');
    return;
  }

  const prices = await fetchPrices([...new Set(holdings.map(h => h.ticker))]);
  let totalVal = 0, totalCost = 0, validN = 0;

  const enriched = holdings.map(h => {
    const q    = prices[h.ticker] || priceCache[h.ticker] || null;
    const cp   = q ? q.price : null;
    const rem  = h.remainingQty || h.qty;
    const cost = h.avgCost * rem;
    const val  = cp ? cp * rem : null;
    const p    = val !== null ? val - cost : null;
    const pPct = p !== null ? (p / cost) * 100 : null;
    totalCost += cost;
    if (val !== null) { totalVal += val; validN++; }
    return { ...h, rem, cp, q, cost, val, pnl: p, pnlPct: pPct };
  });

  const totalPnl = validN ? totalVal - totalCost : null;
  const totalRet = totalPnl !== null ? (totalPnl / totalCost) * 100 : null;

  // שווי תיק = שווי שוק של ההחזקות + מזומן (המזומן נמשך מ-IBKR או מוזן ידנית).
  // החזקה שאין לה מחיר חי נספרת לפי עלות הבסיס שלה.
  const holdingsDispVal = enriched.reduce((s, h) => s + (h.val ?? h.cost), 0);
  document.getElementById('ps-val').textContent  = '$' + Math.round(holdingsDispVal + investCash).toLocaleString();
  setPsValSub(investCash
    ? `החזקות $${Math.round(holdingsDispVal).toLocaleString()} + מזומן $${Math.round(investCash).toLocaleString()}`
    : '');
  document.getElementById('ps-cost').textContent = '$' + Math.round(totalCost).toLocaleString();

  const psPnl = document.getElementById('ps-pnl');
  psPnl.textContent = totalPnl !== null ? fmtD(totalPnl) : '—';
  psPnl.style.color = totalPnl !== null ? pnlCol(totalPnl) : '';

  const psRet = document.getElementById('ps-ret');
  psRet.textContent = totalRet !== null ? signStr(totalRet) + totalRet.toFixed(2) + '%' : '—';
  psRet.style.color = totalRet !== null ? pnlCol(totalRet) : '';

  // Charts
  document.getElementById('port-charts-row').style.display = 'grid';
  const allocData  = enriched.map(h => h.val || h.cost);
  const allocTotal = allocData.reduce((a, b) => a + b, 0);

  if (allocChart) { allocChart.destroy(); allocChart = null; }
  allocChart = new Chart(document.getElementById('alloc-chart'), {
    type: 'doughnut',
    data: { labels: enriched.map(h => h.ticker), datasets: [{ data: allocData, backgroundColor: PORT_COLORS.slice(0, enriched.length), borderWidth: 0, hoverOffset: 4 }] },
    options: { responsive: true, maintainAspectRatio: false, plugins: { legend: { display: false }, tooltip: { callbacks: { label: c => c.label + ': ' + ((c.parsed / allocTotal) * 100).toFixed(1) + '%' } } }, cutout: '65%' },
  });

  document.getElementById('alloc-legend').innerHTML = enriched.map((h, i) => {
    const pct = allocTotal ? ((allocData[i] / allocTotal) * 100).toFixed(1) : 0;
    return `<div class="port-legend-item"><div class="port-legend-dot" style="background:${PORT_COLORS[i % PORT_COLORS.length]}"></div><span class="port-legend-name">${h.ticker}${h.sector ? ' · ' + h.sector : ''}</span><span class="port-legend-pct">${pct}%</span></div>`;
  }).join('');

  if (perfChart) { perfChart.destroy(); perfChart = null; }
  const perfData = enriched.map(h => h.pnlPct !== null ? +h.pnlPct.toFixed(2) : 0);
  perfChart = new Chart(document.getElementById('perf-chart'), {
    type: 'bar',
    data: { labels: enriched.map(h => h.ticker), datasets: [{ data: perfData, backgroundColor: perfData.map(v => v >= 0 ? '#2DD4A0' : '#F87171'), borderRadius: 5, maxBarThickness: 56 }] },
    options: {
      responsive: true, maintainAspectRatio: false,
      plugins: { legend: { display: false }, tooltip: { callbacks: { label: c => (c.parsed.y >= 0 ? '+' : '') + c.parsed.y.toFixed(2) + '%' } } },
      scales: {
        x: { grid: { display: false }, ticks: { font: { size: 11, family: "'IBM Plex Mono'" }, color: 'var(--tx3)' } },
        y: { grid: { color: 'rgba(255,255,255,0.04)' }, border: { display: false }, ticks: { font: { size: 10 }, color: 'var(--tx3)', callback: v => (+v).toFixed(1) + '%' } },
      },
    },
  });

  document.getElementById('port-holdings').innerHTML =
    `<div style="font-size:10.5px;font-weight:500;color:var(--tx3);text-transform:uppercase;letter-spacing:0.8px;margin-bottom:8px">${enriched.length} החזקות${validN < enriched.length ? ' · ' + (enriched.length - validN) + ' ללא מחיר' : ''}</div>` +
    enriched.map((h, i) => buildHoldingCard(h, i, allocData, allocTotal)).join('');

  enriched.forEach(h => { if (h.cp) flash(document.getElementById('phprice-' + h.id), h.cp, h.ticker + '_p'); });
  document.getElementById('port-upd').textContent = 'עודכן ' + new Date().toLocaleTimeString('he-IL', { hour: '2-digit', minute: '2-digit' });
  setDot('port', validN ? 'green' : 'amber', validN ? 'חי' : 'ללא נתונים');
  btn.classList.remove('spinning');
}

