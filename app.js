// Build the tab row HTML — single source of truth used by render + switch
function buildFATabsHtml(reports, activeId) {
  return reports.map(r =>
    `<button class="fa-report-tab${r.id === activeId ? ' active' : ''}" onclick="switchFAReport('${r.id}')">${r.quarter} ${r.year}</button>`
  ).join('') + '<button class="fa-add-report-btn" onclick="faAddReport()"><i class="ti ti-plus" style="font-size:11px"></i>הוסף דוח</button>';
}

function sortFAReports(reports) {
  const qOrder = { 'Q1':0, 'Q2':1, 'Q3':2, 'Q4':3, 'שנתי':4 };
  return [...reports].sort((a, b) => {
    const yDiff = (parseInt(a.year) || 0) - (parseInt(b.year) || 0);
    if (yDiff !== 0) return yDiff;
    return (qOrder[a.quarter] ?? 5) - (qOrder[b.quarter] ?? 5);
  });
}

function renderFAReports() {
  const d = faDataStore[faCurrentTicker];
  if (!d.reports?.length) {
    faCurrentReportId = null;
    document.getElementById('fa-tabs-row').innerHTML = '<button class="fa-add-report-btn" onclick="faAddReport()"><i class="ti ti-plus" style="font-size:11px"></i>הוסף דוח</button>';
    document.getElementById('fa-reports-container').innerHTML = '<div style="text-align:center;padding:2rem;color:var(--tx3);font-size:12.5px"><i class="ti ti-file-text" style="font-size:28px;display:block;margin-bottom:0.5rem;opacity:0.3"></i>אין דוחות עדיין. לחץ "הוסף דוח" להתחיל.</div>';
    return;
  }
  d.reports = sortFAReports(d.reports);
  if (!faCurrentReportId || !d.reports.find(r => r.id === faCurrentReportId)) {
    faCurrentReportId = d.reports[d.reports.length - 1].id;
  }
  document.getElementById('fa-tabs-row').innerHTML          = buildFATabsHtml(d.reports, faCurrentReportId);
  document.getElementById('fa-reports-container').innerHTML = d.reports.map(r => buildReportPanel(r)).join('');
  document.querySelectorAll('.fa-report-panel').forEach(p => p.classList.toggle('active', p.dataset.rid === faCurrentReportId));
}

function switchFAReport(rid) {
  faCurrentReportId = rid;
  document.getElementById('fa-tabs-row').innerHTML = buildFATabsHtml(faDataStore[faCurrentTicker].reports, rid);
  document.querySelectorAll('.fa-report-panel').forEach(p => p.classList.toggle('active', p.dataset.rid === rid));
}

// Build highlight list HTML — single source of truth used by render + add + remove
function buildHighlightHtml(highlights, rid) {
  if (!highlights?.length) return '<div style="font-size:11px;color:var(--tx3);text-align:center;padding:0.5rem">אין היילייטס עדיין</div>';
  return highlights.map((h, hi) =>
    `<div class="fa-hl-item ${h.type}"><span class="fa-hl-badge ${h.type}">${HL_LABEL[h.type]}</span><span class="fa-hl-txt">${escHtml(h.text)}</span><button class="fa-hl-del" onclick="faRemoveHighlight('${rid}',${hi})"><i class="ti ti-x"></i></button></div>`
  ).join('');
}

