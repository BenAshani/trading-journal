// עלות הפוזיציות הפתוחות ביומן — "מזומן שתפוס בעסקאות"
function openTradesCost() {
  return trades.filter(t => t.status === 'open')
    .reduce((s, t) => s + (t.entry || 0) * (t.remainingQty ?? t.qty ?? 0), 0);
}

